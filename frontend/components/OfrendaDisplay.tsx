'use client';

interface OfrendaProps {
  ofrenda: {
    id: string;
    name: string;
    birth_year?: number;
    death_year?: number;
    relationship?: string;
    narrative?: string;
    voice_url?: string;
    historical_context?: {
      events: string[];
      songs: string[];
      news?: string[];
      era_summary?: string;
    };
    created_at: string;
  };
}

export default function OfrendaDisplay({ ofrenda }: OfrendaProps) {
  const API = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:3001';
  const fullVoiceUrl = ofrenda.voice_url
    ? (ofrenda.voice_url.startsWith('http') ? ofrenda.voice_url : `${API}${ofrenda.voice_url}`)
    : null;

  return (
    <article>
      {/* Header candles */}
      <div className="flex justify-center gap-8 mb-8 opacity-60">
        {[...Array(7)].map((_, i) => (
          <div key={i} className="flex flex-col items-center gap-1">
            <div className="candle-flame" style={{ animationDelay: `${i * 0.25}s`, width: i === 3 ? '16px' : '10px', height: i === 3 ? '28px' : '18px' }} />
            <div className="bg-gradient-to-b from-amber-100 to-amber-200 rounded-sm opacity-80"
              style={{ width: i === 3 ? '8px' : '6px', height: i === 3 ? '20px' : '14px' }} />
          </div>
        ))}
      </div>

      {/* Marigold separator */}
      <div className="petal-sep text-2xl mb-8">🌼 ✦ 🌼</div>

      {/* Name & dates */}
      <div className="text-center mb-10">
        <h1 className="font-display text-4xl md:text-5xl text-amber-400 mb-3"
          style={{ fontFamily: 'Playfair Display, serif', textShadow: '0 0 30px rgba(245,158,11,0.3)' }}>
          {ofrenda.name}
        </h1>
        {(ofrenda.birth_year || ofrenda.death_year) && (
          <p className="text-amber-600 text-xl tracking-widest">
            {ofrenda.birth_year ?? '?'} — {ofrenda.death_year ?? '?'}
          </p>
        )}
        {ofrenda.relationship && (
          <p className="text-amber-700 italic mt-2">{ofrenda.relationship}</p>
        )}
      </div>

      {/* Voice player — ElevenLabs audio */}
      {fullVoiceUrl && (
        <div className="mb-10 bg-altar-card border border-amber-900/30 rounded-2xl p-6">
          <div className="flex items-center gap-3 mb-4">
            <span className="text-2xl">🎙️</span>
            <div>
              <p className="text-amber-400 font-semibold">Voice Tribute</p>
              <p className="text-amber-800 text-xs">Narrated by ElevenLabs · Written by Gemma (open-weight AI)</p>
            </div>
          </div>
          <audio controls className="w-full" src={fullVoiceUrl}>
            Your browser does not support audio playback.
          </audio>
        </div>
      )}

      {/* Narrative — generated by Gemma */}
      {ofrenda.narrative && (
        <div className="mb-10 bg-altar-card border border-amber-900/30 rounded-2xl p-8">
          <div className="flex items-center gap-2 mb-6">
            <span className="text-xl">✦</span>
            <span className="text-amber-600 text-sm uppercase tracking-widest">Memorial, written by Gemma</span>
          </div>
          <div className="narrative-prose whitespace-pre-line">
            {ofrenda.narrative}
          </div>
        </div>
      )}

      {/* Historical context — from SerpApi */}
      {ofrenda.historical_context && (
        <div className="mb-10 grid grid-cols-1 md:grid-cols-2 gap-4">
          {/* Events */}
          {ofrenda.historical_context.events?.length > 0 && (
            <div className="bg-altar-card border border-amber-900/20 rounded-xl p-5">
              <h3 className="text-amber-500 font-semibold mb-3 flex items-center gap-2">
                <span>📜</span> Events of their era
              </h3>
              <ul className="space-y-2">
                {ofrenda.historical_context.events.slice(0, 4).map((e, i) => (
                  <li key={i} className="text-amber-100/60 text-sm flex gap-2">
                    <span className="text-amber-800">•</span>{e}
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* Songs */}
          {ofrenda.historical_context.songs?.length > 0 && (
            <div className="bg-altar-card border border-amber-900/20 rounded-xl p-5">
              <h3 className="text-amber-500 font-semibold mb-3 flex items-center gap-2">
                <span>🎵</span> Music of their time
              </h3>
              <ul className="space-y-2">
                {ofrenda.historical_context.songs.slice(0, 4).map((s, i) => (
                  <li key={i} className="text-amber-100/60 text-sm flex gap-2">
                    <span className="text-amber-800">♪</span>{s}
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}

      {/* Footer */}
      <div className="petal-sep text-xl my-8">✿ ✦ ✿</div>
      <div className="text-center text-amber-900 text-sm">
        <p className="italic">Que en paz descanse · May they rest in peace</p>
        <p className="text-xs mt-2">
          This tribute was generated with <a href="https://ai.google.dev/gemma" className="text-amber-800 hover:text-amber-600">Gemma</a> (open-weight AI),
          narrated by ElevenLabs, and stored permanently in Tiger Data + MongoDB Atlas.
        </p>
      </div>
    </article>
  );
}
